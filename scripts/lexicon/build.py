    b = Builder(Path(root), Path(out))
    # Order matters a little: dictionaries with good readings first, so
    # later sources (HSK lists, related verbs, arabeyes) attach to them.
    b.chinese()
    b.japanese()
    b.european()
    b.russian()
    b.arabic()
    b.conjugator()
    b.polyglot()
    b.ctalk()
    b.finish()


