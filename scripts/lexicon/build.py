    def arabic(self):
        print('Arabic')
        c = self.db('ds/data-arabic/atalk_full_vocabulary.sqlite')
        if c:
            for ar, voc, root, lemma, pos, tr, gloss, definition, source, freq in c.execute(
                    'SELECT arabic, vocalized, root, lemma, pos, transliteration, gloss, definition, source, frequency FROM vocabulary'):
                src = {'arabeyes': 'arabeyes', 'curated': 'atalk_curated', 'hanswehr': 'hanswehr'}.get(source, 'arabeyes')
                extra = {k: v for k, v in (('vocalized', voc), ('root', root), ('lemma', lemma)) if v and v != ar}
                eid = self.entry(src, 'ar', ar, tr or '', pos, freq=freq or None, extra=extra)
                self.sense(src, eid, gloss, definition=definition)
        a = self.db('ds/data-arabic/arabeyes.sqlite')
        if a:
            for ar, en in a.execute('SELECT ar, en FROM dict'):
                eid = self.find('ar', (ar or '').strip()) or self.entry('arabeyes', 'ar', ar)
                if eid:
                    self.entry_existing_pivot(eid, 'arabeyes')
                self.sense('arabeyes', eid, en)
        h = self.db('ds/data-arabic/hanswehr.sqlite')
        if h:
            translit = dict(h.execute('SELECT id, transliteration FROM TRANSLITERATION'))
            for _id, word, definition, is_root, parent in h.execute('SELECT id, word, definition, is_root, parent_id FROM DICTIONARY'):
                eid = self.entry('hanswehr', 'ar', word, translit.get(_id) or '', 'root' if is_root else '', ext_id=str(_id),
                                 extra={'parent_id': parent} if parent else None)
                self.sense('hanswehr', eid, (definition or '')[:300], definition=definition)
            for surah, ayah, word, root in h.execute('SELECT SURAH, AYAH, WORD, ROOT_WORD FROM QURAN'):
                # WORD is the word's position in the ayah, not its text.
                self.form('quran_roots', 'ar', root, None, root, f'{surah}:{ayah}:{word}')
        v = self.db('ds/data-arabic/vocab_cache.sqlite')
        if v:
            for row in v.execute('SELECT token, vocalized, stem, root, pos_tag, reading_academic, gloss, definition FROM token_cache'):
                token, voc, stem, root, pos, reading, gloss, definition = row
                eid = self.entry('atalk_cache', 'ar', token, reading or '', pos, extra={k: x for k, x in (('vocalized', voc), ('stem', stem), ('root', root)) if x})
                self.sense('atalk_cache', eid, gloss, definition=definition)
        cv = self.db('ds/data-arabic/conversions.sqlite')
        if cv:
            for slug, raw, style, tash, res, created in cv.execute('SELECT slug, raw_text, translit_style, auto_tashkeel, result_json, created_at FROM conversions'):
                self.t['texts'].add(self.t['texts'].n + 1, 'ar', slug, raw or '', None, {'app': 'A-Talk'}, self.src['demo_texts'])
                self.counts['demo_texts'] += 1

    def entry_existing_pivot(self, eid, src):
        sid = self.src[src]
        if (eid, sid) not in self.pivot:
            self.pivot.add((eid, sid))
            self.t['entry_sources'].add(eid, sid, None)
            self.counts[src] += 1

    # ── Conjugations (cooljugator) ─────────────────────────────
    def conjugator(self):
        print('Conjugator')
        c = self.db('ds/all-conjugation-data/conjugator.db')
        if not c:
            return
        verb_entry = {}
        for vid, code, verb, meaning, pron, url, translit in c.execute(
                'SELECT id, lang_code, verb, meaning, pronunciation, source_url, transliteration FROM verbs'):
            lang = LANG_MAP.get(code, code)
            eid = self.entry('cooljugator', lang, verb, translit or '', CONJ_POS.get(code, 'verb'), ext_id=url,
                             extra={'pronunciation': pron} if pron else None)
            verb_entry[vid] = (eid, lang)
            self.sense('cooljugator', eid, meaning)
        cur = c.execute('SELECT verb_id, table_title, tense, pronoun, form, form_trans, transliteration, row_order, col_order FROM conjugations')
        for vid, title, tense, pronoun, form, ftrans, translit, ro, co in cur:
            e = verb_entry.get(vid)
            if not e or not form:
                continue
            self.t['conj_forms'].add(self.t['conj_forms'].n + 1, e[0], self.src['cooljugator'], title or '', tense or '', pronoun or '',
                                     form.strip(), ftrans or None, translit or None, (ro or 0) * 100 + (co or 0))
            self.counts['cooljugator'] += 1
        for vid, target, en in c.execute('SELECT verb_id, sentence_target, sentence_en FROM examples'):
            e = verb_entry.get(vid)
            if not e or not target:
                continue
            self.t['sentences'].add(self.t['sentences'].n + 1, e[1], target, None, en, 'en', e[0], None, self.src['cooljugator'])
            self.counts['cooljugator'] += 1
        for vid, rel, meaning in c.execute('SELECT verb_id, related_verb, related_meaning FROM related_verbs'):
            e = verb_entry.get(vid)
            if not e:
                continue
            other = self.find(e[1], rel) or self.entry('cooljugator', e[1], rel, '', 'verb')
            self.sense('cooljugator', other, meaning)
            self.t['links'].add(self.t['links'].n + 1, e[0], other, 'related', None, None, self.src['cooljugator'])
            self.counts['cooljugator'] += 1

    # ── 19parse polyglot registry ──────────────────────────────
    def polyglot(self):
        print('Polyglot registry')
        c = self.db('ds/translations-data/database.sqlite')
        if not c:
            return
        ids = {}
        for wid, lang, word, nw, cnt, pos, cat, note, translit in c.execute(
                'SELECT id, language_code, word, normalized_word, count, pos, category, note, transliteration FROM words'):
            ids[wid] = self.entry('polyglot_registry', lang, word, translit or '', pos or '', extra={'count': cnt, 'category': cat} if cat else {'count': cnt})
        for a, b, btype, conf, note in c.execute('SELECT source_word_id, target_word_id, bond_type, confidence, registry_note FROM translation_bonds'):
            if ids.get(a) and ids.get(b):
                self.t['links'].add(self.t['links'].n + 1, ids[a], ids[b], 'translation', conf, btype, self.src['polyglot_registry'])
                self.counts['polyglot_registry'] += 1
        for lang, text, translit, tr_en, cat, note, toks in c.execute(
                'SELECT language_code, original_text, transliteration, translation_en, category, note, tokens_json FROM sentences'):
            self.t['sentences'].add(self.t['sentences'].n + 1, lang, text, translit, tr_en, 'en', None, {'category': cat} if cat else None, self.src['polyglot_registry'])
            self.counts['polyglot_registry'] += 1
        for row in c.execute('SELECT char, script, subscript, pinyin, furigana, onyomi, kunyomi, transliteration, meaning, radical, stroke_count, grade_or_hsk FROM character_dictionary'):
            ch, script, sub, py, fu, on, kun, tr, meaning, rad, strokes, grade = row
            readings = {k: v for k, v in (('pinyin', py), ('furigana', fu), ('on', on), ('kun', kun), ('translit', tr)) if v}
            self.t['chars'].add(self.t['chars'].n + 1, ch, sub or script or '', readings, meaning, rad, strokes if isinstance(strokes, int) else None, None,
                                {'grade_or_hsk': grade} if grade else None, None, self.src['polyglot_chars'])
            self.counts['polyglot_chars'] += 1

    # ── C-Talk (articles, audio, concepts) + other clone demo texts ──
    def ctalk(self):
        print('C-Talk / demo texts')
        seen = set()
        for rel in ('pc/19ctalks/ctalk.db', 'talks/15ctalk/ctalk.db'):
            c = self.db(rel)
            if not c:
                continue
            cols = [r[1] for r in c.execute('PRAGMA table_info(articles)')]
            lang_col = 'lang' if 'lang' in cols else "'zh'"
            for row in c.execute(f'SELECT type, hsk_level, category, title_zh, title_pinyin, title_en, date_str, audio_url, overview_zh, overview_en, content_json, {lang_col} FROM articles'):
                typ, hsk, cat, tzh, tpy, ten, date, audio, ovzh, oven, content, lang = row
                key = (tzh, date)
                if key in seen:
                    continue
                seen.add(key)
                tid = self.t['texts'].add(self.t['texts'].n + 1, lang or 'zh', tzh or '', content or '', f'HSK{hsk}' if hsk else None,
                                          {k: v for k, v in (('type', typ), ('category', cat), ('title_pinyin', tpy), ('title_en', ten), ('date', date),
                                                             ('overview_zh', ovzh), ('overview_en', oven)) if v}, self.src['easymandarin'])
                self.counts['easymandarin'] += 1
                if audio:
                    self.t['media'].add(self.t['media'].n + 1, lang or 'zh', 'audio', audio, tid, self.src['easymandarin'])
                    self.counts['easymandarin'] += 1
            for _id, title, content, opt, created in c.execute('SELECT id, title, content, convert_option, created_at FROM shares'):
                self.t['texts'].add(self.t['texts'].n + 1, 'zh', title or '', content or '', None, {'app': 'C-Talk'}, self.src['demo_texts'])
                self.counts['demo_texts'] += 1
        c = self.db('pc/19ctalks/ctalk.db')
        if c:
            concept = {}
            for cid, key, cat, en, pos in c.execute('SELECT id, concept_key, category, en_gloss, pos FROM multilingual_concepts'):
                concept[cid] = self.entry('ctalk_multilingual', 'en', key, '', pos or '', extra={'category': cat})
                self.sense('ctalk_multilingual', concept[cid], en)
            for row in c.execute('SELECT concept_id, lang, word, translit, reading, pos, root_or_radical, definition, sample_sentence, sample_translation FROM multilingual_words'):
                cid, lang, word, translit, reading, pos, root, definition, ss, st = row
                eid = self.entry('ctalk_multilingual', lang, word, reading or translit or '', pos or '', extra={'root': root} if root else None)
                self.sense('ctalk_multilingual', eid, definition)
                if concept.get(cid) and eid:
                    self.t['links'].add(self.t['links'].n + 1, concept[cid], eid, 'concept', None, None, self.src['ctalk_multilingual'])
                if ss:
                    self.t['sentences'].add(self.t['sentences'].n + 1, lang, ss, None, st, 'en', eid, None, self.src['ctalk_multilingual'])
            for a, b, rtype, note in c.execute('SELECT source_concept_id, target_concept_id, relation_type, note FROM multilingual_relations'):
                if concept.get(a) and concept.get(b):
                    self.t['links'].add(self.t['links'].n + 1, concept[a], concept[b], rtype or 'related', None, note, self.src['ctalk_multilingual'])
        j = self.db('ds/data-japanese/dictionary.db')
        if j:
            for _id, slug, title, content in j.execute('SELECT id, slug, title, content FROM conversions'):
                self.t['texts'].add(self.t['texts'].n + 1, 'ja', title or slug or '', content or '', None, {'app': 'J-Talk'}, self.src['demo_texts'])
                self.counts['demo_texts'] += 1

    # ── output ─────────────────────────────────────────────────
    def finish(self):
        with open(self.out / 'entries.tsv', 'w', encoding='utf-8') as f:
            for (lang, hw, reading, pos), (eid, freq, level, extra) in self.entries.items():
                f.write('\t'.join(esc(x) for x in (eid, lang, hw, norm(lang, hw), reading, pos, freq, level, extra)) + '\n')
        with open(self.out / 'sources.tsv', 'w', encoding='utf-8') as f:
            for code, (name, url, lic, lic_url, vis, origin, notes) in SOURCES.items():
                attribution = f'{name} — {lic}' + (f' ({url})' if url else '')
                f.write('\t'.join(esc(x) for x in (self.src[code], code, name, url, lic, lic_url, attribution, vis, origin, notes)) + '\n')
        for t in self.t.values():
            t.close()
        report = {
            'entries': len(self.entries),
            'tables': {n: t.n for n, t in self.t.items()},
            'rows_per_source': self.counts,
            'entries_per_lang': {},
        }
        for (lang, *_rest) in self.entries:
            report['entries_per_lang'][lang] = report['entries_per_lang'].get(lang, 0) + 1
        report['entries_per_lang'] = dict(sorted(report['entries_per_lang'].items(), key=lambda kv: -kv[1]))
        (self.out / 'report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2))
        print(json.dumps({k: report[k] for k in ('entries', 'tables')}, indent=2))


